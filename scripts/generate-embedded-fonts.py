#!/usr/bin/env python3
"""Regenerate Sources/FIGletKit/EmbeddedFonts.swift from ASCIIKeyboard/Resources/Fonts/*.flf.

Run from the repo root after adding or changing a font:
    python3 scripts/generate-embedded-fonts.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
fonts_dir = root / "ASCIIKeyboard/Resources/Fonts"
out = root / "Sources/FIGletKit/EmbeddedFonts.swift"

def ident(name: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", name)
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return "_" + s if s[0].isdigit() else s

chunks = [
    "// GENERATED by scripts/generate-embedded-fonts.py from ASCIIKeyboard/Resources/Fonts. Do not edit.\n",
    "import Foundation\n\n",
    "/// FIGlet fonts compiled into the binary, so the renderer works without font files on disk.\n",
    "public enum EmbeddedFonts {\n",
    "    /// (name, .flf contents) for every bundled font, sorted by name.\n",
    "    public static let all: [(name: String, content: String)] = [\n",
]
files = sorted(fonts_dir.glob("*.flf"), key=lambda p: p.stem.lower())
chunks += [f'        ("{p.stem}", {ident(p.stem)}),\n' for p in files]
chunks.append("    ]\n")
for p in files:
    text = p.read_text(encoding="latin-1").rstrip("\n")
    assert '"""##' not in text and "\\##" not in text, p
    # Swift source can't contain control characters (bubble/digital use DEL as hardblank):
    # write them as raw-string escapes instead.
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", lambda m: "\\##u{%X}" % ord(m.group()), text)
    chunks.append(f'\n    public static let {ident(p.stem)} = ##"""\n{text}\n"""##\n')
chunks.append("}\n")
out.write_text("".join(chunks), encoding="utf-8")
print(f"wrote {out.relative_to(root)} with {len(files)} fonts")
